  function getFilteredList(){
    let list = activeFilter==="All" ? [...PRODUCTS] : PRODUCTS.filter(p=>p.color===activeFilter);
    if(activeCategory!=="All") list = list.filter(p=>(p.category||"")===activeCategory);
    const q = searchInput.value.trim().toLowerCase();
    if(q){
      list = list.filter(p=> p.title.toLowerCase().includes(q) || p.color.toLowerCase().includes(q) || (p.category||"").toLowerCase().includes(q));
    }
    const sortVal = sortSelect.value;
    if(sortVal==="price-asc") list.sort((a,b)=>a.price-b.price);
    else if(sortVal==="price-desc") list.sort((a,b)=>b.price-a.price);
    else if(sortVal==="name-asc") list.sort((a,b)=>a.title.localeCompare(b.title));
    return list;
  }

