  // Live product sources, in priority order — each step fails silently so
  // the shop never breaks:
  //   1. Sanity CMS (js/sanity.js) — instant updates, no redeploy
  //   2. products.json — file-based backup
  //   3. FALLBACK_PRODUCTS above — embedded offline backup
  function loadLiveProducts(){
    var sanity = (window.__MJ_SANITY__ && window.__MJ_SANITY__.fetchProducts)
      ? window.__MJ_SANITY__.fetchProducts()
      : Promise.reject(new Error("sanity not configured"));
    return sanity.catch(function(){
      return fetch("products.json").then(function(r){
        if(!r.ok) throw new Error("HTTP "+r.status);
        return r.json();
      }).then(function(data){
        if(!Array.isArray(data) || data.length===0) throw new Error("empty products.json");
        return data;
      });
    });
  }
  loadLiveProducts().then(useProducts).catch(function(){ /* keep fallback data */ });
